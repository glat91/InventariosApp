    val estadoId: Int?,
    val ciudadId: Int?,
    val localidad: String?,
    val direccion: String?,
    val colonia: String?,
    val calle: String?,
    val codigoPostal: String?,
    val noExterior: String?,
    val noInterior: String?,
    val telefono: String?,
