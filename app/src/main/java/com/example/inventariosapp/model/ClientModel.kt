    val clienteId: Int,
    val tipoPersonaId: Int?,
    val tipoPersona: String?,
    val tipoGiroId: Int?,
    val tipoGiro: String?,
    val tipoPagoId: Int?,
    val tipoPago: String?,
    val nombreCliente: String?,
    val razonSocial: String?,
    val rfc: String?,
